let currentLang = 'en';
let currentCurrency = 'ETB';

let exchangeRates = {
    'ETB': 1,
    'USD': 0.0086,
    'EUR': 0.0080,
    'GBP': 0.0068
};

const currencySymbols = {
    'ETB': ' ETB',
    'USD': '$',
    'EUR': '€',
    'GBP': '£'
};

async function fetchLiveRates() {
    try {
        const response = await fetch('https://open.er-api.com/v6/latest/ETB');
        const data = await response.json();
        if (data && data.rates) {
            exchangeRates['USD'] = data.rates.USD;
            exchangeRates['EUR'] = data.rates.EUR;
            exchangeRates['GBP'] = data.rates.GBP;
            changeCurrency(currentCurrency);
        }
    } catch (error) {
        console.log("Error fetching live rates, using fallback rates:", error);
    }
}

function toggleLanguage() {
    currentLang = currentLang === 'en' ? 'ti' : 'en';
    
    const elements = document.querySelectorAll('[data-key]');
    elements.forEach(el => {
        const key = el.getAttribute('data-key');
        if (translations[currentLang] && translations[currentLang][key]) {
            el.innerText = translations[currentLang][key];
        }
    });

    const langBtn = document.getElementById('lang-btn');
    if (langBtn) {
        langBtn.innerText = currentLang === 'en' ? 'Switch to ትግርኛ' : 'Change to English';
    }

    changeCurrency(currentCurrency);
}

function changeCurrency(selectedCurrency) {
    currentCurrency = selectedCurrency;
    const rate = exchangeRates[currentCurrency];
    const symbol = currencySymbols[currentCurrency];

    const priceElements = document.querySelectorAll('[data-key^="price-"]');
    
    priceElements.forEach(el => {
        const key = el.getAttribute('data-key');
        const originalText = translations['en'][key]; 
        
        if (originalText) {
            const originalPrice = parseFloat(originalText.replace(/[^0-9]/g, ''));
            
            if (currentCurrency === 'ETB') {
                if (currentLang === 'ti') {
                    el.innerText = originalPrice + ' ብር';
                } else {
                    el.innerText = originalPrice + ' ETB';
                }
            } else {
                const convertedPrice = (originalPrice * rate).toFixed(2);
                el.innerText = symbol + convertedPrice;
            }
        }
    });
}

// --- ጽፉፍን ዝተወሃሃደ ሰክሽን መርኣዪ ፎንክሽን (FIXED) ---
function showSection(sectionId, btn) {
    // 1. ንኹሎም ዋና Section-ታትን Sub-section-ታትን ፈለማ ሓብኦም
    document.querySelectorAll('.section').forEach(s => s.classList.remove('active'));
    document.querySelectorAll('.sub-section').forEach(sub => sub.classList.remove('active'));

    // 2. እቲ ዝተጠወቐ Button ካብቶም ዓበይቲ ዋና ታባት (Food, Drinks, Room Service) እንተኾይኑ
    if (btn && !btn.classList.contains('sub-tab')) {
        document.querySelectorAll('.tab').forEach(t => t.classList.remove('active'));
        btn.classList.add('active');

        // ንኡሳን ታባት ጉጅለታት (Sub-tabs Group) ምሕባእን ምኽፋትን
        document.querySelectorAll('.sub-tabs-group').forEach(g => g.classList.remove('active'));
        
        if (sectionId === 'food') {
            const foodGroup = document.getElementById('food-subs');
            if (foodGroup) {
                foodGroup.classList.add('active');
                // ብኣውቶማቲክ ነቲ ቀዳማይ ንኡስ ታብ (Breakfast) ንምኽፋት
                const firstSub = foodGroup.querySelector('.sub-tab');
                if (firstSub) firstSub.click();
                return;
            }
        } else if (sectionId === 'drinks') {
            const drinksGroup = document.getElementById('drinks-subs');
            if (drinksGroup) {
                drinksGroup.classList.add('active');
                // ብኣውቶማቲክ ነቲ ቀዳማይ ንኡስ ታብ (Hot Drinks) ንምኽፋት
                const firstSub = drinksGroup.querySelector('.sub-tab');
                if (firstSub) firstSub.click();
                return;
            }
        } else if (sectionId === 'roomservice') {
            // Room Service እንተኾይኑ ንኡስ ታብ ስለዘይብሉ ንዕኡ ጥራሕ ነንቅሆ
            const target = document.getElementById('roomservice');
            if (target) target.classList.add('active');
            return;
        }
    } 
    
    // 3. እቲ ዝተጠወቐ Button ናይ ውሽጢ ንኡስ ታብ (Sub Tab) እንተኾይኑ
    if (btn && btn.classList.contains('sub-tab')) {
        const parentGroup = btn.closest('.sub-tabs-group');
        if (parentGroup) {
            parentGroup.querySelectorAll('.sub-tab').forEach(st => st.classList.remove('active'));
            parentGroup.classList.add('active');
            
            // ነቲ ምስዚ ንኡስ ታብ ዝኸይድ ዓብዪ ዋና ታብ እውን active ግበሮ
            document.querySelectorAll('.tab').forEach(t => t.classList.remove('active'));
            if (parentGroup.id === 'food-subs') {
                document.querySelector('[data-key="tab-food"]').classList.add('active');
                document.getElementById('food').classList.add('active');
            } else if (parentGroup.id === 'drinks-subs') {
                document.querySelector('[data-key="tab-drinks"]').classList.add('active');
                document.getElementById('drinks').classList.add('active');
            }
        }
        btn.classList.add('active');
    }

    // 4. ነቲ ዝተመርጸ ንኡስ ክፍሊ (Target Sub-section) ንጡፍ ግበሮ
    const targetSub = document.getElementById(sectionId);
    if (targetSub) {
        targetSub.classList.add('active');
    }
}

// --- ብሰዓት ሪኢኻ ብኣውቶማቲክ ናይ ምኽፋት ሎጂክ (FIXED) ---
window.onload = function() {
    fetchLiveRates(); 

    const currentHour = new Date().getHours();
    let autoSectionId = 'breakfast'; 
    let targetTabKey = 'sub-breakfast';

    // ሰዓት ርእይካ ዝኽፈት ምምራጽ
    if (currentHour >= 6 && currentHour < 12) {
        autoSectionId = 'breakfast'; 
        targetTabKey = 'sub-breakfast';
    } else if (currentHour >= 12 && currentHour < 16) {
        autoSectionId = 'lunch'; 
        targetTabKey = 'sub-lunch';
    } else {
        autoSectionId = 'dinner'; 
        targetTabKey = 'sub-dinner';
    }

    // ነቲ ናይቲ ሰዓት ንኡስ ታብ ንምጽዋዕ
    const targetSubTab = document.querySelector(`[data-key="${targetTabKey}"]`);
    if (targetSubTab) {
        showSection(autoSectionId, targetSubTab);
    }
};

function togglePaymentDropdown(dropdownId, event) {
    event.stopPropagation(); 
    document.querySelectorAll('.pay-dropdown').forEach(dropdown => {
        if (dropdown.id !== dropdownId) {
            dropdown.classList.remove('show');
        }
    });
    const targetDropdown = document.getElementById(dropdownId);
    if (targetDropdown) {
        targetDropdown.classList.toggle('show');
    }
}

function copyAccount(accNumber, buttonElement) {
    navigator.clipboard.writeText(accNumber).then(() => {
        const originalText = buttonElement.innerText;
        buttonElement.innerText = "Copied!";
        buttonElement.style.background = "#4CAF50"; 
        buttonElement.style.color = "#ffffff";
        setTimeout(() => {
            buttonElement.innerText = originalText;
            buttonElement.style.background = "var(--primary-color)";
            buttonElement.style.color = "#000000";
        }, 2000);
    }).catch(err => {
        console.error("Could not copy text: ", err);
    });
}

function filterMenu() {
    const searchQuery = document.getElementById('menu-search').value.toLowerCase();
    const menuItems = document.querySelectorAll('.menu-item');
    
    menuItems.forEach(item => {
        const itemName = item.querySelector('.item-name') ? item.querySelector('.item-name').innerText.toLowerCase() : '';
        const itemDesc = item.querySelector('.item-desc') ? item.querySelector('.item-desc').innerText.toLowerCase() : '';
        if (itemName.includes(searchQuery) || itemDesc.includes(searchQuery)) {
            item.style.display = ""; 
        } else {
            item.style.display = "none"; 
        }
    });

    const categoryLabels = document.querySelectorAll('.category-label');
    categoryLabels.forEach(label => {
        if (searchQuery.length > 0) {
            label.style.display = "none";
        } else {
            label.style.display = "";
        }
    });
}

function toggleCurrencyMenu(event) {
    event.stopPropagation(); 
    const menu = document.getElementById('currency-options');
    if (menu) {
        menu.classList.toggle('open');
        const arrow = document.querySelector('.custom-select-trigger .arrow');
        if (menu.classList.contains('open')) {
            arrow.style.transform = 'rotate(180deg)';
        } else {
            arrow.style.transform = 'rotate(0deg)';
        }
    }
}

function selectCurrency(currencyCode, labelText) {
    document.getElementById('selected-currency').innerText = labelText;
    document.querySelectorAll('.option-item').forEach(item => {
        item.classList.remove('active');
        if (item.innerText === labelText) {
            item.classList.add('active');
        }
    });
    changeCurrency(currencyCode);
    const menu = document.getElementById('currency-options');
    if(menu) menu.classList.remove('open');
    document.querySelector('.custom-select-trigger .arrow').style.transform = 'rotate(0deg)';
}

window.addEventListener('click', function() {
    const menu = document.getElementById('currency-options');
    if (menu) {
        menu.classList.remove('open');
        const arrow = document.querySelector('.custom-select-trigger .arrow');
        if(arrow) arrow.style.transform = 'rotate(0deg)';
    }
    document.querySelectorAll('.pay-dropdown').forEach(dropdown => {
        dropdown.classList.remove('show');
    });
});
