let currentLang = 'en';

// ቋንቋ ንምቕያር (Toggle Function)
function toggleLanguage() {
    currentLang = currentLang === 'en' ? 'ti' : 'en';
    
    // ንኹሎም data-key ዘለዎም ኤለመንትታት ትርጉም ምትካእ
    const elements = document.querySelectorAll('[data-key]');
    elements.forEach(el => {
        const key = el.getAttribute('data-key');
        if (translations[currentLang][key]) {
            el.innerText = translations[currentLang][key];
        }
    });

    // ናይቲ Button ጽሑፍ ጥራሕ ንምቕያር
    const langBtn = document.getElementById('lang-btn');
    if(langBtn) {
        langBtn.innerText = translations[currentLang]['btn-lang'];
    }
}

// ዝተፈላለዩ ክፍልታት (Food, Drinks, Room Service) ንምርኣይ
function showSection(sectionId, btn) {
    // ኩሎም ክፍልታት ምሕባእ
    document.querySelectorAll('.section').forEach(s => s.classList.remove('active'));
    
    // ነቲ ዝተመርጸ ክፍሊ ጥራሕ ምርኣይ
    const targetSection = document.getElementById(sectionId);
    if(targetSection) {
        targetSection.classList.add('active');
    }

    // ንኹሎም Tabs Active class ምእላይ
    document.querySelectorAll('.tab').forEach(t => t.classList.remove('active'));
    
    // ነቲ ዝተጸቐጠ Tab ጥራሕ Active ምግባር
    if(btn) {
        btn.classList.add('active');
    }
}

// ገጽ ምስ ተኸፍተ QR Code ንምድላው
window.onload = function() {
    const qrContainer = document.getElementById("qr-code");
    if (qrContainer) {
        new QRCode(qrContainer, {
            text: window.location.href, // እቲ ዘለኻዮ ናይ ገጽ ሊንክ ይወስድ
            width: 150,
            height: 150,
            colorDark: "#c9a84c", // ወርቃማ ሕብሪ
            colorLight: "#ffffff"
        });
    }
};

// QR Code ንምውራድ
function downloadQR() {
    const canvas = document.querySelector('#qr-code canvas');
    if (canvas) {
        const link = document.createElement('a');
        link.download = 'kingdom-menu-qr.png';
        link.href = canvas.toDataURL();
        link.click();
    }
}
